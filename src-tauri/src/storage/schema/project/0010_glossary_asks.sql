-- О чём цепочка автоперевода спросила модель и не получила годного ответа: термин, подпись говорящего, токен,
-- имя персонажа. Такую запись цепочка не спрашивает снова, и сводка её не считает: шаг становится пустым.
-- Кнопка раздела в окне глоссария спрашивает всё без перевода, не глядя на отметки.
CREATE TABLE glossary_asks (
  kind     TEXT NOT NULL CHECK (kind IN ('term', 'speaker', 'token', 'name')),
  key      TEXT NOT NULL,           -- term: ключ названия; speaker: ключ говорящего; token: имя;
                                    -- name: «номер персонажа:поле:ключ написания»
  asked_at INTEGER NOT NULL,
  PRIMARY KEY (kind, key)
) STRICT;
